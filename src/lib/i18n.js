export function getLang(cookieStr) {
  const m = String(cookieStr || "").match(/faberp_lang=([a-z]{2})/);
  const code = m?.[1];
  return LANGS.find((l) => l.code === code) || LANGS[0];
}

// translate: English text is the key; unknown keys fall back to English.
export function makeT(langCode) {
  const d = DICT[langCode];
  if (!d) return (s) => s;
  return (s) => d[s] ?? s;
}
